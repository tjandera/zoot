// Generates supabase/seed.sql from src/data (places + sidequests). `npm run seed:sql`
import { readFileSync, writeFileSync } from 'node:fs'
import { nearestHub } from '../src/lib/travel.js'
import { SIDEQUESTS } from '../src/data/sidequests.js'

const places = JSON.parse(readFileSync(new URL('../src/data/places.sg.json', import.meta.url)))
const q = (v) => (v == null ? 'null' : `'${String(v).replace(/'/g, "''")}'`)
const arr = (a) => (a?.length ? `array[${a.map(q).join(', ')}]::text[]` : `'{}'::text[]`)
const ints = (a) => (a?.length ? `array[${a.join(', ')}]::int[]` : `'{}'::int[]`)

const rows = places.map((p) => `  (${[
  q(p.id), q(p.name), q(p.area), p.lat, p.lng, arr(p.tags), p.duration_min, p.cost_band ?? 1, p.indoor,
  q(nearestHub(p).name), `${q(JSON.stringify(p.hours ?? '24h'))}::jsonb`, ints(p.closed_days), p.min_window_h ?? 'null',
  q(p.blurb), arr(p.captions), q(p.safety_notes), q(p.image_url), q(p.image_credit)
].join(', ')})`)

const sq = SIDEQUESTS.map((s) => `  (${[q(s.id), q(s.place_id), q(s.title), s.stay_min, s.xp].join(', ')})`)

const sql = `-- Generated by scripts/gen-seed.mjs — do not edit by hand. ${places.length} places, ${SIDEQUESTS.length} sidequests.
insert into public.places (id, name, area, lat, lng, tags, duration_min, cost_band, indoor, mrt, hours, closed_days, min_window_h, blurb, captions, safety_notes, image_url, image_credit) values
${rows.join(',\n')}
on conflict (id) do update set
  name = excluded.name, area = excluded.area, lat = excluded.lat, lng = excluded.lng, tags = excluded.tags,
  duration_min = excluded.duration_min, cost_band = excluded.cost_band, indoor = excluded.indoor, mrt = excluded.mrt,
  hours = excluded.hours, closed_days = excluded.closed_days, min_window_h = excluded.min_window_h, blurb = excluded.blurb,
  captions = excluded.captions, safety_notes = excluded.safety_notes, image_url = excluded.image_url, image_credit = excluded.image_credit;

insert into public.sidequests (id, place_id, title, extra_min, xp) values
${sq.join(',\n')}
on conflict (id) do update set place_id = excluded.place_id, title = excluded.title, extra_min = excluded.extra_min, xp = excluded.xp;

-- Sample advisory so the P1 alerts slot has data. Clearly marked as demo content.
insert into public.advisories (area, severity, source, headline, starts, ends)
select 'Marina Bay', 2, 'Zoot demo data', 'Demo: afternoon thunderstorms likely — outdoor stops may be swapped indoor.', now(), now() + interval '1 day'
where not exists (select 1 from public.advisories where source = 'Zoot demo data');
`
writeFileSync(new URL('../supabase/seed.sql', import.meta.url), sql)
console.log(`supabase/seed.sql written: ${places.length} places, ${SIDEQUESTS.length} sidequests`)
